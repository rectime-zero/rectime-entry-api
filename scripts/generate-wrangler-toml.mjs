import { mkdir, readFile, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const __filename = fileURLToPath(import.meta.url)
const __dirname = path.dirname(__filename)
const rootDir = path.resolve(__dirname, '..')
const outputPath = path.join(rootDir, 'wrangler.toml')
const localEnvPath = path.join(rootDir, '.dev.vars')

const ROOT_PREFIX = 'WRANGLER_ROOT_'
const VAR_PREFIX = 'WRANGLER_VAR_'
const TABLE_PREFIX = 'WRANGLER_TABLE_'

function parseEnvFile(content) {
  const env = {}

  for (const rawLine of content.split(/\r?\n/)) {
    const line = rawLine.trim()
    if (!line || line.startsWith('#')) {
      continue
    }

    const separatorIndex = line.indexOf('=')
    if (separatorIndex === -1) {
      continue
    }

    const key = line.slice(0, separatorIndex).trim()
    let value = line.slice(separatorIndex + 1).trim()

    if ((value.startsWith('"') && value.endsWith('"')) || (value.startsWith("'") && value.endsWith("'"))) {
      value = value.slice(1, -1)
    }

    env[key] = value
  }

  return env
}

async function readLocalEnvFile() {
  try {
    const content = await readFile(localEnvPath, 'utf8')
    return parseEnvFile(content)
  } catch (error) {
    if (error && typeof error === 'object' && 'code' in error && error.code === 'ENOENT') {
      return {}
    }
    throw error
  }
}

function readGithubVars() {
  const raw = process.env.GITHUB_VARS_JSON?.trim()
  if (!raw) {
    return {}
  }

  const parsed = JSON.parse(raw)
  if (!parsed || typeof parsed !== 'object' || Array.isArray(parsed)) {
    throw new Error('GITHUB_VARS_JSON must be a JSON object')
  }

  return parsed
}

async function buildConfigEnvMap() {
  const envMap = new Map()

  for (const [key, value] of Object.entries(await readLocalEnvFile())) {
    if (typeof value === 'string') {
      envMap.set(key, value)
    }
  }

  for (const [key, value] of Object.entries(readGithubVars())) {
    if (typeof value === 'string') {
      envMap.set(key, value)
    }
  }

  for (const [key, value] of Object.entries(process.env)) {
    if (typeof value === 'string') {
      envMap.set(key, value)
    }
  }

  return envMap
}

function normalizeValue(value) {
  const trimmed = value.trim()

  if (trimmed === 'true') {
    return true
  }

  if (trimmed === 'false') {
    return false
  }

  if (/^-?\d+(\.\d+)?$/.test(trimmed)) {
    return Number(trimmed)
  }

  return trimmed
}

function quoteTomlString(value) {
  return `"${value.replace(/\\/g, '\\\\').replace(/"/g, '\\"')}"`
}

function formatTomlValue(value) {
  if (typeof value === 'string') {
    return quoteTomlString(value)
  }

  if (typeof value === 'number' || typeof value === 'boolean') {
    return String(value)
  }

  throw new Error(`Unsupported TOML value type: ${typeof value}`)
}

function readRequired(config, key) {
  const value = config.root[key]
  if (value === undefined) {
    throw new Error(`Missing required config: ${ROOT_PREFIX}${key.toUpperCase()}`)
  }
  return value
}

function parseConfig(envMap) {
  const root = {}
  const vars = {}
  const tables = new Map()

  for (const [key, rawValue] of envMap.entries()) {
    const value = rawValue.trim()
    if (!value) {
      continue
    }

    if (key.startsWith(ROOT_PREFIX)) {
      root[key.slice(ROOT_PREFIX.length).toLowerCase()] = normalizeValue(value)
      continue
    }

    if (key.startsWith(VAR_PREFIX)) {
      vars[key.slice(VAR_PREFIX.length)] = normalizeValue(value)
      continue
    }

    if (!key.startsWith(TABLE_PREFIX)) {
      continue
    }

    const tableMatch = key.slice(TABLE_PREFIX.length).match(/^(.+?)_(\d+)_(.+)$/)
    if (!tableMatch) {
      throw new Error(`Invalid table config key: ${key}`)
    }

    const [, rawTableName, rawIndex, rawField] = tableMatch
    const index = Number(rawIndex)
    if (!Number.isInteger(index)) {
      throw new Error(`Invalid table index in key: ${key}`)
    }

    const field = rawField.toLowerCase()
    const tableName = rawTableName.toLowerCase()
    const tableKey = `${tableName}:${index}`

    if (!tables.has(tableKey)) {
      tables.set(tableKey, {
        tableName,
        index,
        fields: {},
      })
    }

    tables.get(tableKey).fields[field] = normalizeValue(value)
  }

  return { root, vars, tables }
}

function buildToml(config) {
  const lines = ['# Generated by scripts/generate-wrangler-toml.mjs']

  const preferredRootKeys = ['name', 'main', 'compatibility_date']
  for (const key of preferredRootKeys) {
    lines.push(`${key} = ${formatTomlValue(readRequired(config, key))}`)
  }

  const otherRootKeys = Object.keys(config.root)
    .filter((key) => !preferredRootKeys.includes(key))
    .sort()

  for (const key of otherRootKeys) {
    lines.push(`${key} = ${formatTomlValue(config.root[key])}`)
  }

  const varEntries = Object.entries(config.vars).sort(([left], [right]) => left.localeCompare(right))
  if (varEntries.length > 0) {
    lines.push('', '[vars]')
    for (const [key, value] of varEntries) {
      lines.push(`${key} = ${formatTomlValue(value)}`)
    }
  }

  const tableEntries = [...config.tables.values()].sort((left, right) => {
    if (left.tableName === right.tableName) {
      return left.index - right.index
    }
    return left.tableName.localeCompare(right.tableName)
  })

  for (const table of tableEntries) {
    lines.push('', `[[${table.tableName}]]`)
    for (const key of Object.keys(table.fields).sort()) {
      lines.push(`${key} = ${formatTomlValue(table.fields[key])}`)
    }
  }

  lines.push('')
  return lines.join('\n')
}

async function main() {
  const config = parseConfig(await buildConfigEnvMap())
  const toml = buildToml(config)

  await mkdir(path.dirname(outputPath), { recursive: true })
  await writeFile(outputPath, toml, 'utf8')
  console.log(`Generated ${path.relative(rootDir, outputPath)}`)
}

main().catch((error) => {
  console.error(error)
  process.exitCode = 1
})